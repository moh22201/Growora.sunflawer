const dicts: Record<Lang, Record<TKey, string>> = { en, fr };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = (dicts[lang] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      // Item ids in vars are translated automatically.
      const val = k === "item" ? translate(lang, `item.${v}`) : String(v);
      s = s.split(`{${k}}`).join(val);
    }
  }
  return s;
}

export function useT() {
  const { lang } = useGame();
  return (key: TKey | string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
